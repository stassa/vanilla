:-module(knf, [target/1
	      ,invented/1
	      ,nonterminal/1
	      ,preterminal/1
		    ]).

:-use_module(project_root(configuration)).

/** <module> A Second-Order Definite Clause encoding of Kuroda Normal Form.

A Noncontracting Grammar (NG) is in Kuroda Normal Form (KNF) when each
of its productions is in one of the the forms:

==
AB --> CD
A --> BC
A --> B
A --> a
==

Where A,B,C,D are nonterminals and a is a terminal. Note that some
sources ommit A --> B. NGs are weakly equivalent to Context Sensitive
Grammars (CSGs) meaning that they generate the same strings, but not
necessarily the same derivations. In short both NGs and CSGs accept and
generate exactly the Context Sensitive Languages (CSLs).

Kuroda Normal Forms can be seen as a genealisation of Chomsky Normal
(CNF) for Context-Free Grammars (CSGs). We already have a Second-Order
Definite Normal Form (SONF) version of CNF (in fact we have
Chomsky-Greibach Normal Form, C-GNF) so it will probably simplify the
development of KNF to base our work C-GNF.

Recall that a CSG is in CNF when each of its productions is in one of
the forms:

==
A --> BC
A --> a
S --> ε
==

Where ε is the empty string. CSGs in KNF do not accept the empty
string, thus only the first two productions of CNF are relevant to KNF.
In C-GNF the first two productions are implemented by the metarules
Chain and Identity, with suitable constraints.  We need one more
metarule for the context-sensitive production AB --> CD. The tricky bit
is that we want to implement our SONF as a DCG (in its unsugar'd form)
but DCGs only have one nonterminal on the left-hand side, so it's not
immediately clear how to represent a context-sensitive rule like AB -->
CD as a DCG production.

For the time being we will use push-back lists to represent the
"context" of a nonterminal on the left-hand side. This way AB --> CD
will be modelled as a DCG production: A,B --> C,D.

In unsugar'd form a DCG production like A, B --> C, D is expanded to:

==
A(x, y) :- C(x, u), D(u, z), B(y, z) [1]
==

We can see this as "pushing" on the input the tokens generated by B//0
immediately after removing the tokens consumed by A//0.

The DCG production in [1] is already a metarule.  Now we can define our
KNF SONF with a context-sensitive metarule of this form and also Chain
and Identity.

For the KNF SONF we have:

==
% AB --> CD
(KNF-AB_CD) P(x, y) :- Q(y, z), R(x, u), S(u, z)
% A --> BC
(Chain) P(x, y) :- Q(x, z), R(z, y)
% A --> a  or A --> B (depending on constraints)
(Identity) P(x, y) :- Q(x, y)
==

For the interest of simplicity (and efficiency) we will ommit rules of
the form A --> B since those would probably only end up adding
complexity to the process of constructing a grammar.

We need to define suitable constraints for our KNF. This is a matter of
trial-and-error and it is ongoing.

*/

:- multifile target/1.
:- multifile invented/1.
:- multifile nonterminal/1.
:- multifile preterminal/1.

% KNF AB --> CD
% DCGs: a,b --> c,d. or a,[b] --> c,d.
configuration:knf_AB_CD metarule 'P(x, y) :- Q(x, u), R(u, z), S(y, z)'.
% KNF A --> B
% Same as Identity but needs different constraints to separate from the
% use of Identity in A --> a
configuration:knf_A_B metarule 'P(x, y) :- Q(x, y)'.
% KNF A --> a
configuration:knf_A_a metarule 'P(x, y) :- Q(x, y)'.
% Tri-Chain is in Weak C-GNF.  As in that SONF it is used here to reduce
% the number of necessary invented predicates.  Instead of inventing one
% new predicate to resolve two instances of Chain, we one instance of
% Tri-Chain can be used instead.
configuration:tri_chain metarule 'P(x,y):- Q(x,z), R(z,u), S(u,y)'.


		/*******************************
		*    UNIVERSAL CONSTRAINTS     *
		*******************************/

% McCarthyite (anti-left recursion) constraint
configuration:metarule_constraints(M,fail):-
	ground(M)
	,M =.. [m,_Id,P,P|_Ps]
	,debug(constraints,'Left-recursion detected! ~w',[M]).

% The first literal on the right-hand side can't be the target: it can
% only be an invented predicate, or a pre-terminal.
% This enforces Greibach Normal Form but allows for invented predicate
% symbols, necessary for Chomsky Normal Form.
configuration:metarule_constraints(M,fail):-
	M =.. [m,_Id,_P,Q|_Ps]
	,ground(Q)
	,target(Q)
	,debug(constraints,'Target first in the RHS! ~w',[M]).

% An invented predicate cannot immediately expand to an invented
% predicate. Eliminates some oblique left-recursions but needs better
% documentation.
configuration:metarule_constraints(M,fail):-
	M =.. [m,_Id,P,Q|_Ps]
	,ground(P)
	,ground(Q)
	,invented(P)
	,invented(Q)
	,debug(constraints,'Invented sequence detected! ~w',[M]).

		/*******************************
		*    KNF_AB-CD CONSTRAINTS     *
		*******************************/

% The start symbol cannot be in the RHS. Breaks weak-CGNF if made
% universal.
configuration:metarule_constraints(M,fail):-
	M =.. [m,knf_AB_CD,_P|Ps]
	,copy_term(Ps,Ps_c)
	,member(P,Ps_c) % ooof.
	,ground(P)
	,target(P)
	,debug(constraints,'Target in the RHS! ~w',[M]).

/* Covered by McCarthyite constraint when pushback list literal is last.
% In AB --> CD A and C cannot be the same or we have Penttonen Normal
% Form. Very tentative attempt to avoid too many instantiations. May
% well cause incompleteness.
configuration:metarule_constraints(m(knf_AB_CD,P,Q,R,S),fail):-
	ground(P)
	,ground(R)
	,P == R
	,debug(constraints,'Penttonen Normal Form detected! ~w',[m(knf_AB_CD,P,Q,R,S)]).
*/

% Allow A,B --> C, D only if B is a preterminal like B --> [b].
% Attempt to improve efficiency of generation and specialisation by
% avoiding more expensive constructions where the context rule is a
% nonterminal but not a preterminal.
configuration:metarule_constraints(m(knf_AB_CD,P,Q,R,S),fail):-
	ground(S)
	,\+ preterminal(S)
	,debug(constraints,'Nonterminal context! ~w',[m(knf_AB_CD,P,Q,R,S)]).


		/*******************************
		*     IDENTITY CONSTRAINTS     *
		*******************************/

% Identity clauses can only be pre-terminals.
% The left hand side must be the target
configuration:metarule_constraints(m(identity,P,Q),fail):-
	ground(P)
        ,\+ target(P)
	,debug(constraints,'LHS must be the target! ~w',[m(identity,P,Q)]).
% The right hand side must be a pre-terminal.
configuration:metarule_constraints(m(identity,P,Q),fail):-
	ground(Q)
        ,\+ preterminal(Q)
	,debug(constraints,'RHS must be a preterminal! ~w',[m(identity,P,Q)]).

% The empty string can only be a pre-terminal.
configuration:metarule_constraints(M,fail):-
	ground(M)
	,M =.. [m,Id,_P|Ps]
	,Id \== identity
        ,memberchk(empty, Ps)
	,debug(constraints,'The empty string must be a preterminal! ~w',[M]).

		/*******************************
		*      CHAIN CONSTRAINTS       *
		*******************************/

% Recursion in chain can only be tail-recursion.
configuration:metarule_constraints(m(chain,P,Q,R),fail):-
	ground(P)
	,ground(Q)
	,P == Q
	,debug(constraints,'Chain can only be tail-recursive! ~w',[m(chain,P,Q,R)]).
configuration:metarule_constraints(m(chain,P,Q,R),fail):-
	ground(Q)
	,ground(R)
	,Q == R
	,debug(constraints,'Chain can only be tail-recursive! ~w',[m(chain,P,Q,R)]).

		/*******************************
		*    TRI-CHAIN CONSTRAINTS     *
		*******************************/

% Recursion in tri-chain can only be tail-recursion or recursion between
% the head and "middle" body literal.
configuration:metarule_constraints(m(tri_chain,P,Q,R,S),fail):-
	ground(P)
	,ground(Q)
	,P == Q
	,debug(constraints,'Over-specialised tri-chain! ~w',[m(tri_chain,P,Q,R,S)]).
configuration:metarule_constraints(m(tri_chain,P,Q,R,S),fail):-
	ground(Q)
	,ground(R)
	,Q == R
	,debug(constraints,'Over-specialised tri-chain! ~w',[m(tri_chain,P,Q,R,S)]).
configuration:metarule_constraints(m(tri_chain,P,Q,R,S),fail):-
	ground(R)
	,ground(S)
	,R == S
	,debug(constraints,'Over-specialised tri-chain! ~w',[m(tri_chain,P,Q,R,S)]).

